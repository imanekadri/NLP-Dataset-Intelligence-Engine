import os
from datetime import datetime

from pipeline.state import NLPPipelineState
from pipeline.config import PipelineConfig


def run_readme_generator(state: NLPPipelineState) -> NLPPipelineState:
    """
    Agent 9 — README Generator.
    Génère un README.md complet pour le dataset traité, à partir du state final.
    """
    config = PipelineConfig()
    config.ensure_dirs()

    profile = state.get("dataset_profile", {})
    dataset_type = state.get("dataset_type", "unknown")
    ml_format = state.get("ml_format", "unknown")
    tasks = state.get("tasks", [])
    labels = state.get("labels", {})
    splits = state.get("splits", {})
    export_paths = state.get("export_paths", {})
    quality_score = state.get("quality_score", 0)
    qa_report = state.get("qa_report", {})
    languages_detected = state.get("languages_detected", {})
    raw_docs = state.get("raw_docs", [])

    stats = profile.get("statistical", {})
    lang_dist = profile.get("language_distribution", {})

    # Distribution des labels
    from collections import Counter
    label_dist = Counter(l.get("category", "unknown") for l in labels.values())

    # Construire le README
    readme = f"""# Dataset: {dataset_type.replace('_', ' ').title()}

> Auto-generated by NLP Dataset Intelligence Engine on {datetime.now().strftime('%Y-%m-%d %H:%M')}

## Overview

| Property | Value |
|---|---|
| Dataset Type | {dataset_type} |
| ML Format | {ml_format} |
| Total Documents | {stats.get('total_docs', len(raw_docs))} |
| Avg Word Count | {stats.get('avg_length_words', 'N/A')} |
| Vocabulary Richness | {stats.get('vocab_richness', 'N/A')} |
| Structure | {profile.get('structure', 'N/A')} |
| Noise Level | {profile.get('noise_level', 'N/A')} |
| Quality Score | {quality_score}/100 |

## Tasks

{chr(10).join(f'- {t}' for t in tasks) if tasks else '- text_classification'}

## Languages

| Language | Count |
|---|---|
{chr(10).join(f'| {lang} | {count} |' for lang, count in lang_dist.items()) if lang_dist else '| N/A | N/A |'}

## Label Distribution

| Label | Count |
|---|---|
{chr(10).join(f'| {label} | {count} |' for label, count in label_dist.most_common()) if label_dist else '| N/A | N/A |'}

## Dataset Splits

| Split | Documents |
|---|---|
| Train | {len(splits.get('train', []))} |
| Validation | {len(splits.get('val', []))} |
| Test | {len(splits.get('test', []))} |

## Export Formats

{chr(10).join(f'- **{fmt}**: `{path}`' for fmt, path in export_paths.items()) if export_paths else '- No exports generated'}

## Quality Report

- **Quality Score**: {quality_score}/100
- **PII Documents**: {qa_report.get('pii_check', {}).get('flagged_documents', 0)}
- **Class Balance Score**: {qa_report.get('class_balance', {}).get('score', 'N/A')}
- **Label Completeness**: {qa_report.get('label_completeness', {}).get('score', 'N/A')}%

### Issues
{chr(10).join(f'- {issue}' for issue in qa_report.get('issues', [])) if qa_report.get('issues') else '- No issues detected'}

## Usage Example

```python
import json

# Load JSONL dataset
with open("output/exports/dataset.jsonl", "r") as f:
    dataset = [json.loads(line) for line in f]

# Filter by split
train = [r for r in dataset if r["split"] == "train"]
print(f"Training samples: {{len(train)}}")
print(f"First sample: {{train[0]['text'][:100]}}")
```

## Pipeline

This dataset was processed by the following agents:

1. **Agent 1 - Ingestion**: Text extraction from {len(set(r['format'] for r in raw_docs))} formats
2. **Agent 2 - Profiler**: Statistical analysis, clustering, topic modeling
3. **Agent 3 - NLP Understanding**: NER, sentiment analysis, PII detection
4. **Agent 4 - Semantic Brain**: Dataset type inference ({dataset_type})
5. **Agent 5 - Auto Label**: Automatic labeling ({len(label_dist)} categories)
6. **Agent 6 - Dataset Architect**: Train/val/test splitting
7. **Agent 7 - Export Engine**: Multi-format export
8. **Agent 8 - QA Agent**: Quality assurance (score: {quality_score}/100)
9. **Agent 9 - README Generator**: This document
"""

    # Sauvegarde
    readme_path = os.path.join(config.REPORTS_DIR, "README_dataset.md")
    with open(readme_path, "w", encoding="utf-8") as f:
        f.write(readme)

    print(f"[Agent 9] README generated: {readme_path}")

    return {**state, "readme_content": readme}
